"""``idp-cli fit-check`` — run sample documents through a stack and report.

A thin call into ``IDPClient.fit_check.run``. Progress goes to stderr; the short
summary goes to stdout, and ``--json`` replaces it with ``fit-report.json`` verbatim.
See docs/fit-check.md.
"""

from __future__ import annotations

import json
import sys
from typing import Any, Dict, Optional

import click
from rich.console import Console
from rich.markup import escape

err_console = Console(stderr=True)


def _summary(report: Dict[str, Any], result: Any) -> str:
    s = report["summary"]
    lines = [
        f"Fit check: {s['documents']} document(s), {s['succeeded']} succeeded, "
        f"{s['failed']} failed ({s['refused']} refused before upload)",
        f"Profile: {report['configuration']['profile']} "
        f"({report['configuration']['generated_by']}); classes: "
        + (", ".join(report["configuration"]["classes"]) or "none"),
    ]
    for c in s["classes"]:
        below = ", ".join(c["fields_below_threshold"]) or "none"
        mean = c["mean_confidence"]
        lines.append(
            f"  {c['class']}: {c['documents']} document(s), mean confidence "
            f"{mean if mean is not None else 'n/a'}, fields below threshold: {below}"
        )
    for t in s["triggered_limitations"]:
        lines.append(f"  {t['ref']}: {t['documents']} document(s)")
    lat = s["latency_seconds"]
    lines.append(
        f"Latency p50 {lat['p50']} s, p90 {lat['p90']} s; estimated cost per page "
        f"{s['estimated_cost_usd_per_page']} USD (an estimate)"
    )
    if report["evaluation"] is None:
        lines.append(
            "No ground truth: confidence is the model's own estimate and is not "
            "accuracy."
        )
    else:
        e = report["evaluation"]
        lines.append(
            f"Evaluation: precision {e['precision']}, recall {e['recall']}, F1 "
            f"{e['f1_score']}, accuracy {e['accuracy']}"
        )
    if result.active_profile_unchanged is not None:
        lines.append(
            "Active profile and Config#default unchanged"
            if result.active_profile_unchanged
            else "WARNING: the active profile or Config#default changed"
        )
    lines.append(f"Report: {result.report_path}")
    lines.append(f"        {result.markdown_path}")
    return "\n".join(lines)


@click.command(name="fit-check")
@click.option(
    "--stack-name", help="CloudFormation stack name (not needed with --from-record)"
)
@click.option(
    "--samples",
    "samples_dir",
    type=click.Path(file_okay=False),
    help="Folder of sample documents (read recursively)",
)
@click.option(
    "--description", help="Plain-language description of the documents, for Quick Start"
)
@click.option(
    "--config-profile",
    help="Use this existing configuration profile instead of generating one",
)
@click.option(
    "--ground-truth",
    "ground_truth_dir",
    type=click.Path(file_okay=False, exists=True),
    help="Folder of baselines, one subfolder per sample file name, to evaluate against",
)
@click.option(
    "--output", "output_dir", help="Report folder (default ./fit-check-<timestamp>/)"
)
@click.option(
    "--cleanup",
    is_flag=True,
    help="Delete the run's inputs, results, baselines and generated profile when done",
)
@click.option(
    "--max-documents", default=50, show_default=True, type=click.IntRange(min=1)
)
@click.option(
    "--timeout",
    "timeout_seconds",
    default=3600,
    show_default=True,
    type=click.IntRange(min=1),
    help="Seconds to wait for processing before reporting unfinished documents",
)
@click.option(
    "--from-record",
    type=click.Path(dir_okay=False, exists=True),
    help="Rebuild the report offline from a fit-run-record.json; uploads nothing",
)
@click.option("--json", "as_json", is_flag=True, help="Print fit-report.json to stdout")
@click.option("--region", help="AWS region (optional)")
def fit_check(
    stack_name: Optional[str],
    samples_dir: Optional[str],
    description: Optional[str],
    config_profile: Optional[str],
    ground_truth_dir: Optional[str],
    output_dir: Optional[str],
    cleanup: bool,
    max_documents: int,
    timeout_seconds: int,
    from_record: Optional[str],
    as_json: bool,
    region: Optional[str],
):
    """Run sample documents through a deployed stack and write a fit report.

    Uploads the samples, processes them under a NEW configuration profile
    generated by Discovery (or Quick Start from --description), or under
    --config-profile, and writes fit-report.json and fit-report.md. The active
    profile is never changed.
    """
    from idp_sdk import IDPClient
    from idp_sdk.exceptions import IDPError

    if not from_record and not (stack_name and samples_dir):
        err_console.print("[red]--stack-name and --samples are required[/red]")
        sys.exit(2)

    def progress(message: str) -> None:
        err_console.print(escape(message))

    try:
        client = IDPClient(stack_name=stack_name, region=region)
        result = client.fit_check.run(
            samples_dir,
            stack_name,
            description=description,
            config_profile=config_profile,
            ground_truth_dir=ground_truth_dir,
            output_dir=output_dir,
            cleanup=cleanup,
            max_documents=max_documents,
            timeout_seconds=timeout_seconds,
            from_record=from_record,
            progress=progress,
        )
    except (IDPError, OSError, ValueError) as e:
        err_console.print(f"[red]✗ {escape(str(e))}[/red]")
        sys.exit(1)

    if as_json:
        click.echo(json.dumps(result.report, indent=2))
    else:
        click.echo(_summary(result.report, result))
