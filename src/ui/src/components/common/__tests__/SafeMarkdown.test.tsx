describe('SafeMarkdown loads nothing from another origin', () => {
  it.each(CORPUS)('%s', (_name, markdown) => {
    expect(offOriginLoads(renderMarkdown(markdown))).toEqual([]);
  });

  it('the corpus is not vacuous: each entry names a remote resource', () => {
    for (const [, markdown] of CORPUS) expect(markdown).toMatch(/remote\.example|amazonaws\.com|javascript:|data:text|blob:/);
    expect(CORPUS.length).toBeGreaterThan(40);
  });

  it('the detector catches each kind of load it is relied on for', () => {
    // A detector that returned [] for everything would pass the corpus above.
    const probe = (html: string): string[] => {
      const div = document.createElement('div');
      div.innerHTML = html;
      return offOriginLoads(div);
    };
    expect(probe(`<img src="${REMOTE}/a.png">`)).not.toEqual([]);
    expect(probe(`<span style="background:url(${REMOTE}/a.png)">x</span>`)).not.toEqual([]);
    expect(probe(`<style>@import "${REMOTE}/a.css";</style>`)).not.toEqual([]);
    expect(probe(`<picture><source srcset="${REMOTE}/a.png"></picture>`)).not.toEqual([]);
    expect(probe(`<table><tbody><tr><td background="${REMOTE}/a.png"></td></tr></tbody></table>`)).not.toEqual([]);
    expect(probe(`<a href="${REMOTE}/">ok</a>`)).toEqual([]);
  });

  it('renders a refused image as a link that shows its URL', () => {
    const container = renderMarkdown(`![chart](${REMOTE}/a.png)`);
    expect(container.querySelector('img')).toBeNull();
    const link = container.querySelector('a');
    expect(link?.getAttribute('href')).toBe(`${REMOTE}/a.png`);
    expect(link?.textContent).toBe(`${REMOTE}/a.png`);
    expect(link?.getAttribute('rel')).toContain('noreferrer');
  });

  it('renders a refused non-web image URL as plain text, not a link', () => {
    const container = renderMarkdown(`<img src="data:text/html;base64,PGI+" alt="x">`);
    expect(container.querySelector('img')).toBeNull();
    expect(container.querySelector('a')).toBeNull();
  });

  it('drops a <style> element together with its CSS text', () => {
    const container = renderMarkdown(`<style>table { border-collapse: collapse; }</style>\n\nAfter`);
    expect(container.querySelector('style')).toBeNull();
    expect(container.textContent).not.toContain('border-collapse');
    expect(container.textContent).toContain('After');
  });

  it('still renders the rest of the text when an image URL carries a malformed escape', () => {
    const container = renderMarkdown(`before ![x](https://s3.amazonaws.com/%E0/x.png) after`);
    expect(container.textContent).toContain('before');
    expect(container.textContent).toContain('after');
    expect(container.querySelector('img')).toBeNull();
  });

  it('allows no S3 image when no deployment settings are available', () => {
    const container = renderMarkdown(`![x](https://${OWN_BUCKET}.s3.us-west-2.amazonaws.com/p.png)`, false);
    expect(container.querySelector('img')).toBeNull();
  });
});

describe('SafeMarkdown still renders what the app relies on', () => {
  const srcOf = (markdown: string): string | null => renderMarkdown(markdown).querySelector('img')?.getAttribute('src') ?? null;

  it.each([
    ['virtual-hosted regional', `https://${OWN_BUCKET}.s3.us-west-2.amazonaws.com/pages/1.jpg?X-Amz-Signature=abc&X-Amz-Expires=300`],
    ['virtual-hosted global', `https://${OWN_BUCKET}.s3.amazonaws.com/pages/1.jpg?X-Amz-Signature=abc`],
    ['GovCloud regional', `https://${OWN_BUCKET}.s3.us-gov-west-1.amazonaws.com/pages/1.jpg?X-Amz-Signature=abc`],
    ['path style', `https://s3.us-east-1.amazonaws.com/${OWN_BUCKET}/pages/1.jpg?X-Amz-Signature=abc`],
    // The shape botocore presigns with endpoint_url=https://bucket.<vpce DNS name> and virtual addressing.
    ['interface endpoint', `https://${OWN_BUCKET}.bucket.vpce-0abc123-def.s3.us-west-2.vpce.amazonaws.com/pages/1.jpg`],
    ['input bucket', `https://${SETTINGS.InputBucket}.s3.us-west-2.amazonaws.com/doc.png`],
  ])('a presigned S3 image for this deployment (%s)', (_name, url) => {
    expect(srcOf(`![page](${url})`)).toBe(url);
    expect(srcOf(`<img src="${url}">`)).toBe(url);
  });

  it('a data: image', () => {
    const url = 'data:image/png;base64,iVBORw0KGgo=';
    expect(srcOf(`![chart](${url})`)).toBe(url);
  });

  it('a same-origin image, absolute or relative', () => {
    expect(srcOf(`![logo](/logo192.png)`)).toBe('/logo192.png');
    expect(srcOf(`![logo](img-1)`)).toBe('img-1');
    expect(srcOf(`![logo](${ORIGIN}/logo192.png)`)).toBe(`${ORIGIN}/logo192.png`);
  });

  it('a blob: image minted by this page', () => {
    const url = `blob:${ORIGIN}/0b6a3c2e-1111-2222-3333-444455556666`;
    expect(srcOf(`<img src="${url}">`)).toBe(url);
  });

  it('links keep their targets', () => {
    const container = renderMarkdown(`[docs](https://docs.example/page) and <mailto:someone@example.com>`);
    const hrefs = Array.from(container.querySelectorAll('a')).map((a) => a.getAttribute('href'));
    expect(hrefs).toEqual(['https://docs.example/page', 'mailto:someone@example.com']);
  });

  it('GFM tables keep their column alignment', () => {
    const container = renderMarkdown('| a | b |\n| :-: | --: |\n| 1 | 2 |');
    const cells = Array.from(container.querySelectorAll('td'));
    expect(cells.map((c) => c.getAttribute('align') ?? c.style.textAlign)).toEqual(['center', 'right']);
  });

  it('the knowledge-base context block keeps details, summary and pre-line', () => {
    const container = renderMarkdown(
      'Answer\n<details><summary>Context</summary><p style="white-space: pre-line;">line 1\nline 2</p></details>',
    );
    expect(container.querySelector('details summary')?.textContent).toBe('Context');
    expect(container.querySelector('details p')?.getAttribute('style')).toBe('white-space: pre-line;');
  });

  const fixture = (name: string): string => readFileSync(join(__dirname, 'fixtures', name), 'utf8');

  it('the evaluation report renders its tables with their inline layout', () => {
    const container = renderMarkdown(fixture('evaluation-report.md'));
    expect(offOriginLoads(container)).toEqual([]);
    expect(container.querySelectorAll('table').length).toBeGreaterThanOrEqual(3);
    const styled = Array.from(container.querySelectorAll('th[style]')).map((th) => th.getAttribute('style') ?? '');
    expect(styled.some((style) => style.includes('padding: 8px') && style.includes('border: 1px solid'))).toBe(true);
    expect(container.querySelector('tr[style]')?.getAttribute('style')).toContain('background');
    expect(container.textContent).toContain('EmployeeName');
  });

  it('the rule-validation summary renders its tables, column widths and status colours, without its <style> block', () => {
    const md = fixture('rule-validation-summary.md');
    expect(md).toContain('<style>'); // the formatter still emits one; it is dropped on render
    const container = renderMarkdown(md);
    expect(offOriginLoads(container)).toEqual([]);
    expect(container.querySelector('style')).toBeNull();
    expect(container.textContent).not.toContain('border-collapse');
    expect(Array.from(container.querySelectorAll('col')).map((c) => c.getAttribute('style'))).toEqual([
      'width: 18%;',
      'width: 12%;',
      'width: 60%;',
      'width: 10%;',
    ]);
    const colours = Array.from(container.querySelectorAll('span[style]')).map((s) => s.getAttribute('style'));
    expect(colours).toContain('color: rgb(22, 171, 57); font-weight: bold;');
    expect(colours).toContain('color: rgb(209, 50, 18); font-weight: bold;');
    expect((container.querySelector('th[style]') as HTMLElement | null)?.style.backgroundColor).toBe('rgb(241, 241, 241)');
    expect(container.textContent).toContain('Income documented');
  });

  it('every style attribute the two report formats emit is accepted by the style rule', () => {
    // Derived from the formatter output, so a new declaration in either report
    // fails here rather than silently losing its layout.
    const styles = new Set<string>();
    for (const name of ['evaluation-report.md', 'rule-validation-summary.md']) {
      for (const m of fixture(name).matchAll(/style=["']([^"']*)["']/g)) styles.add(m[1]);
    }
    expect(styles.size).toBeGreaterThan(5);
    expect([...styles].filter((s) => !STYLE_ATTRIBUTE_VALUE.test(s))).toEqual([]);
  });
});

describe('safe-markdown-policy', () => {
  it('the schema renders neither <style>, <picture> nor <source>, and strips <style> text', () => {
    expect(safeSchema.tagNames).not.toContain('style');
    expect(safeSchema.tagNames).not.toContain('picture');
    expect(safeSchema.tagNames).not.toContain('source');
    expect(safeSchema.strip).toContain('style');
  });

  it('no element in the schema may carry an unrestricted style attribute or a second URL attribute', () => {
    for (const [tag, attrs] of Object.entries(safeSchema.attributes)) {
      for (const attr of attrs as ReadonlyArray<string | readonly unknown[]>) {
        const name = typeof attr === 'string' ? attr : String(attr[0]);
        expect(name === 'style' && typeof attr === 'string', `${tag} allows any style`).toBe(false);
        expect(
          ['srcSet', 'srcset', 'poster', 'background', 'longDesc', 'ping', 'data'].includes(name) && tag !== '*',
          `${tag} allows ${name}`,
        ).toBe(false);
      }
    }
  });

  it.each([
    ['https://b.s3.amazonaws.com/k', 'b'],
    ['https://my.dotted.bucket.s3.us-west-2.amazonaws.com/k', 'my.dotted.bucket'],
    ['https://s3.us-west-2.amazonaws.com/b/k', 'b'],
    ['https://s3-us-west-2.amazonaws.com/b/k', 'b'],
    ['https://b.s3.dualstack.us-east-1.amazonaws.com/k', 'b'],
    ['https://b.bucket.vpce-01-ab.s3.us-west-2.vpce.amazonaws.com/k', 'b'],
    ['https://bucket.vpce-01-ab.s3.us-west-2.vpce.amazonaws.com/b/k', 'b'],
    ['https://b.vpce-01-ab.s3.us-west-2.vpce.amazonaws.com/k', null],
    ['https://s3.amazonaws.com/%E0/k', null],
    ['https://b.s3.cn-north-1.amazonaws.com.cn/k', 'b'],
    ['https://b.s3-fips.us-gov-west-1.amazonaws.com/k', 'b'],
    ['https://own.s3-other.s3.amazonaws.com/k', 'own.s3-other'],
    ['https://own.s3.other.s3.amazonaws.com/k', 'own.s3.other'],
    ['https://b.s3-accesspoint.us-east-1.amazonaws.com/k', null],
    ['https://b.s3-evil.amazonaws.com/k', null],
    ['https://b.execute-api.us-west-2.amazonaws.com/k', null],
    ['https://b.s3.amazonaws.com.remote.example/k', null],
    ['http://b.s3.amazonaws.com/k', null],
    ['https://remote.example/b/k', null],
  ])('s3BucketOf(%s) = %s', (url, bucket) => {
    expect(s3BucketOf(new URL(url))).toBe(bucket);
  });
});
