/**
 * Rendered markdown loads resources only from the app's own origins.
 *
 * Each corpus entry is markdown or embedded HTML that names an image, stylesheet or
 * other resource on `remote.example`. After rendering, the DOM is searched as a
 * whole rather than for the one element each entry is about: no element other than
 * an `<a href>` (a navigation the reader chooses) may carry a URL in any attribute
 * unless it is an `<img src>` the policy allows, no `style` attribute may contain a
 * CSS function or escape, and no element that can load a resource on its own
 * (`style`, `link`, `source`, `svg`, `iframe`, ...) may be present at all.
 *
 * The positive half renders this deployment's own S3 URLs, `data:`/`blob:` and
 * same-origin images, and the two report formats the backend emits, generated by the
 * real `idp_common` formatters into `fixtures/` (evaluation `to_markdown()` and the
 * rule-validation `_format_summary_as_markdown()`), and asserts their tables,
 * inline layout styles and status colours survive.
 */

