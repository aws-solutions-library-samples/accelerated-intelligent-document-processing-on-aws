const OWN_BUCKET = 'idp-stack-outputbucket-abc123';
const SETTINGS = {
  OutputBucket: OWN_BUCKET,
  InputBucket: 'idp-stack-inputbucket-def456',
  PublicArtifactsBucket: 'shared-public-artifacts',
  StackName: 'idp-stack',
};
const ORIGIN = window.location.origin;

const renderMarkdown = (markdown: string, withSettings = true): HTMLElement => {
  const tree = <SafeMarkdown>{markdown}</SafeMarkdown>;
  const { container } = render(
    withSettings ? <SettingsContext.Provider value={{ settings: SETTINGS }}>{tree}</SettingsContext.Provider> : tree,
  );
  return container;
};

/** Elements that fetch something by being present, whatever their attributes say. */
const LOADING_ELEMENTS = [
  'style',
  'link',
  'source',
  'picture',
  'svg',
  'image',
  'iframe',
  'frame',
  'object',
  'embed',
  'video',
  'audio',
  'track',
  'script',
  'meta',
  'base',
  'input[type=image]',
  'use',
  'feimage',
];
/** Anything in an attribute value that names another resource. */
const URL_SHAPE = /(?:[a-z][a-z0-9+.-]*:|\/\/|\\\\)/i;

/**
 * The detector's own notion of an allowed image, written independently of the
 * policy under test: a detector that called `isAllowedImageUrl` would accept
 * whatever a broken policy accepts.
 */
const ownImage = (src: string): boolean => {
  if (/^data:image\//i.test(src) || src.startsWith(`blob:${ORIGIN}/`)) return true;
  let url: URL;
  try {
    url = new URL(src, `${ORIGIN}/`);
  } catch {
    return false;
  }
  if (url.origin === ORIGIN) return !src.includes('\\');
  if (url.protocol !== 'https:' || !url.hostname.endsWith('.amazonaws.com')) return false;
  // Exact host shapes only: one optional region label, or the interface-endpoint form.
  const host = url.hostname;
  const label = '[a-z0-9-]+';
  return [OWN_BUCKET, SETTINGS.InputBucket].some(
    (b) =>
      new RegExp(`^${b}\\.s3(?:\\.${label})?\\.amazonaws\\.com$`).test(host) ||
      new RegExp(`^${b}\\.bucket\\.vpce-${label}\\.s3\\.${label}\\.vpce\\.amazonaws\\.com$`).test(host) ||
      (new RegExp(`^s3(?:\\.${label})?\\.amazonaws\\.com$`).test(host) && url.pathname.startsWith(`/${b}/`)),
  );
};

/** Every way the rendered DOM could make the browser fetch from somewhere else. */
const offOriginLoads = (container: HTMLElement): string[] => {
  const problems: string[] = [];
  for (const selector of LOADING_ELEMENTS) {
    if (container.querySelector(selector)) problems.push(`<${selector}> present`);
  }
  for (const el of Array.from(container.querySelectorAll('*'))) {
    const tag = el.tagName.toLowerCase();
    for (const attr of Array.from(el.attributes)) {
      const value = attr.value;
      if (tag === 'a' && attr.name === 'href') continue;
      if (tag === 'img' && attr.name === 'src') {
        if (!ownImage(value)) problems.push(`<img src="${value}">`);
        continue;
      }
      if (attr.name === 'style') {
        // React re-serialises the attribute through the CSSOM, so colours come back
        // as rgb(...); what matters is that no declaration can name a resource.
        if (/url\s*\(|image-set|expression|@import|\\|\/\/|remote/i.test(value)) problems.push(`<${tag} style="${value}">`);
        continue;
      }
      if (
        attr.name === 'srcset' ||
        attr.name === 'poster' ||
        attr.name === 'background' ||
        attr.name === 'longdesc' ||
        attr.name === 'ping'
      ) {
        problems.push(`<${tag} ${attr.name}="${value}">`);
        continue;
      }
      if (URL_SHAPE.test(value) || /remote\.example/i.test(value)) problems.push(`<${tag} ${attr.name}="${value}">`);
    }
  }
  return problems;
};

