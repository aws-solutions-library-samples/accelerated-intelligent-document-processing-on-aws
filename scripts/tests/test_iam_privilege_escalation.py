"""Repo-wide gate on IAM permission-mutation actions in CloudFormation templates.

Motivated by **AppSec finding b2b397a9** (High). The Security Invariant scan's
``iam-role-without-privilege-escalation`` check, scenario 1.1, found that
``AgentCoreGatewayManagerFunctionRole`` "can add permissions to itself":
``AgentCoreGatewayManagerFunction``'s inline policy granted ``iam:CreateRole``,
``iam:AttachRolePolicy`` and ``iam:PassRole`` on ``Resource: "*"``, so the role
could attach ``AdministratorAccess`` to itself and escalate out of every other
boundary in the stack. It was never needed — the function is a CloudFormation
custom resource that creates one AgentCore Gateway against a role
CloudFormation has already built for it (see ``src/lambda/
agentcore_gateway_manager/index.py``).

The fix removed those actions. Nothing stopped them coming back, and the SI scan
runs against a *deployed* account rather than a PR, so a reintroduction would
ship and only be caught on the next scan. This gate closes that gap at review
time.

Rule enforced: **no IAM policy statement in any template may grant an action
that mutates IAM permissions** — unless the template is in
``DEPLOYMENT_ROLE_TEMPLATES``, which lists, with justification, the few roles
that exist precisely in order to create the stack's roles.

A statement grants an action when an ``Action`` pattern matches it (IAM
wildcards, case-insensitive) or, for ``NotAction``, when its list does not
exclude it: ``Allow`` + ``NotAction: [kms:Decrypt]`` grants every IAM mutation
(issue #1767). ``NotResource`` counts as every resource it does not name.

``iam:PassRole`` is deliberately NOT in ``MUTATION_ACTIONS``. Passing a role is
not adding a permission, and a custom resource that hands an execution role to
a service legitimately needs it; the risk in ``PassRole`` is its *resource*
scope, which is what ``test_pass_role_is_scoped`` covers separately.

Two known seams, both shared with the sibling gate in
``test_lambda_log_groups.py``:

* **``Fn::If`` is expanded, but only in the 3-arity form.** A malformed
  ``Fn::If`` is invisible here; cfn-lint rejects it, so nothing ships.
* **``Fn::ForEach`` / ``Transform: AWS::LanguageExtensions`` is invisible.** A
  ``Fn::ForEach::X`` key under ``Resources`` maps to a list, so a policy
  generated by it is not scanned. The repo does not use it today (checked); if
  that changes, this gate must be taught about it rather than trusted.
"""

