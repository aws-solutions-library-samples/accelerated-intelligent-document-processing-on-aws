@pytest.mark.unit
def test_discovery_prunes_scratch(tmp_path: Path) -> None:
    """A template under ``scratch/`` (e.g. a stale git worktree) is not scanned.

    ``scratch/`` is gitignored local work. A worktree left there is a complete
    copy of the repo, so every exempt deployment-role template reappears under
    a path the exemption list does not name — and both rules fail on files that
    are not part of the tree under review.
    """
    stray = tmp_path / "scratch" / "wt-old" / "iam-roles" / "role.yaml"
    stray.parent.mkdir(parents=True)
    stray.write_text(
        "Resources:\n"
        "  R:\n"
        "    Type: AWS::IAM::Role\n"
        "    Properties:\n"
        "      Policies:\n"
        "        - PolicyName: p\n"
        "          PolicyDocument:\n"
        "            Statement:\n"
        "              - Effect: Allow\n"
        "                Action: iam:AttachRolePolicy\n"
        "                Resource: '*'\n"
    )
    real = tmp_path / "svc" / "template.yaml"
    real.parent.mkdir(parents=True)
    real.write_text("Resources:\n  B:\n    Type: AWS::S3::Bucket\n")
    assert [p.relative_to(tmp_path) for p in _template_paths(root=tmp_path)] == [
        Path("svc/template.yaml")
    ]
    assert not _scan(root=tmp_path), "the gate scanned a template under scratch/"


@pytest.mark.unit
def test_exemptions_are_not_stale() -> None:
    """Every allowlisted template must still exist and still need the exemption.

    A stale entry is worse than none: it reads as a reviewed decision while
    silently covering nothing, and it would hide a genuine regression if the
    path were ever reused.
    """
    stale = []
    unnecessary = []
    for rel, reason in DEPLOYMENT_ROLE_TEMPLATES.items():
        path = REPO_ROOT / rel
        if not path.exists():
            stale.append(rel)
            continue
        assert reason.strip(), f"{rel}: exemption has no justification"
        if not _offending_actions(_load_text(path.read_text())):
            unnecessary.append(rel)

    assert not stale, (
        f"DEPLOYMENT_ROLE_TEMPLATES names template(s) that no longer exist: "
        f"{stale}. Remove the stale entries."
    )
    assert not unnecessary, (
        f"DEPLOYMENT_ROLE_TEMPLATES exempts template(s) that no longer grant any "
        f"permission-mutation action: {unnecessary}. Remove the exemption so the "
        f"rule protects them."
    )
